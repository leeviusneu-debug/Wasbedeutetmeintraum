export function getSymbol(slug: string) {
  return DREAM_SYMBOLS.find((symbol) => symbol.slug === slug);
}

export function getRelatedSymbols(symbol: DreamSymbol) {
  return symbol.related
    .map((slug) => getSymbol(slug))
    .filter((related): related is DreamSymbol => Boolean(related));
}

export function symbolPath(slug: string) {
  return `/traumdeutung/${slug}`;
}
